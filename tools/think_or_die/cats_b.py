def word_pair(id, rule_kind, en, ru, n=0, value_en=None, value_ru=None, en_ok=True, ru_ok=True):
    for lang, title, val, ok in (("en", en, value_en, en_ok), ("ru", ru, value_ru, ru_ok)):
        if not ok: continue
        r = {"kind": rule_kind, "lang": lang}
        if n: r["n"] = n
        if val: r["value"] = val
        cat(f"{id}_{lang}", "WORD_RULE", "vocabulary", title[0], title[1], "", "", "", "", langs=[lang], rule=r)

